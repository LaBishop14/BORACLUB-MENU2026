/* =====================================
   MOBILE SWIPE
===================================== */

let touchStartX = 0;

let touchEndX = 0;


viewerSwipeArea.addEventListener(
    "touchstart",
    function(event) {

        touchStartX =
            event.changedTouches[0]
                .screenX;

    },
    {
        passive: true
    }
);


viewerSwipeArea.addEventListener(
    "touchend",
    function(event) {

        touchEndX =
            event.changedTouches[0]
                .screenX;


        handleSwipe();

    },
    {
        passive: true
    }
);



function handleSwipe() {

    const swipeDistance =
        touchEndX - touchStartX;


    const minimumSwipe =
        50;


    /* SWIPE LEFT = NEXT */

    if (
        swipeDistance <
        -minimumSwipe
    ) {

        nextViewerImage();

    }


    /* SWIPE RIGHT = PREVIOUS */

    if (
        swipeDistance >
        minimumSwipe
    ) {

        previousViewerImage();

    }

}