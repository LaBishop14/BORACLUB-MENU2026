    document.getElementById("viewerClose");

const viewerPrev =
    document.getElementById("viewerPrev");

const viewerNext =
    document.getElementById("viewerNext");

const viewerSwipeArea =
    document.getElementById("viewerSwipeArea");


let viewerItems = [];

let viewerIndex = 0;



function getVisibleViewerItems() {

    viewerItems = Array.from(
        document.querySelectorAll(
            ".menu-card"
        )
    ).filter(card => {

        return (
            card.style.display !== "none"
            &&
            card.closest(".menu-section")
                .style.display !== "none"
        );

    });

}



function openViewer(card) {

    getVisibleViewerItems();


    viewerIndex =
        viewerItems.indexOf(card);


    if (viewerIndex < 0) {
        viewerIndex = 0;
    }


    updateViewer();


    imageViewer.classList.remove(
        "hidden"
    );


    document.body.style.overflow =
        "hidden";

}



function updateViewer() {

    if (
        viewerItems.length === 0
    ) {
        return;
    }


    if (
        viewerIndex < 0
    ) {

        viewerIndex =
            viewerItems.length - 1;

    }


    if (
        viewerIndex >=
        viewerItems.length
    ) {

        viewerIndex = 0;

    }


    const card =
        viewerItems[viewerIndex];


    const cardImage =
        card.querySelector("img");


    const name =
        card.querySelector("h3")
            ?.textContent
            ?.trim()
        || "";


    const description =
        card.querySelector(
            ".item-description"
        )
        ?.textContent
        ?.trim()
        || "";


    const price =
        card.querySelector(
            ".item-price"
        )
        ?.textContent
        ?.trim()
        || "";


    viewerImage.src =
        cardImage.src;


    viewerImage.alt =
        name;


    viewerName.textContent =
        name;


    viewerDescription.textContent =
        description;


    viewerPrice.textContent =
        price;


    viewerCounter.textContent =
        `${viewerIndex + 1} / ${viewerItems.length}`;

}



function closeViewer() {

    imageViewer.classList.add(
        "hidden"
    );


    document.body.style.overflow =
        "";

}



function previousViewerImage() {

    viewerIndex--;

    updateViewer();

}



function nextViewerImage() {

    viewerIndex++;

    updateViewer();

}



